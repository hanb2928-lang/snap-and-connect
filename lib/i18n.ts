export const translations: Record<AppLanguage, TranslationDict> = { ko, en, ja, vi, es, zh };

export function detectSystemLanguage(): AppLanguage {
  if (typeof navigator !== 'undefined' && navigator.language) {
    const lang = navigator.language.toLowerCase().slice(0, 2);
    if (lang in translations) return lang as AppLanguage;
  }
  return 'ko';
}

export function translate(lang: AppLanguage, key: string, fallback?: string): string {
  const dict = translations[lang] || translations.ko;
  return dict[key] ?? fallback ?? translations.ko[key] ?? key;
}
