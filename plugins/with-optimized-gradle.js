function withProguardRules(config) {
  return withDangerousMod(config, [
    'android',
    (cfg) => {
      const proguardPath = path.join(
        cfg.modRequest.platformProjectRoot,
        'app',
        'proguard-rules.pro'
      );
      fs.writeFileSync(proguardPath, PROGUARD_RULES, 'utf8');
      return cfg;
    },
  ]);
}

// ── Compose all three plugins ─────────────────────────────────────────────────
function withOptimizedGradle(config) {
  config = withGradleProps(config);
  config = withHermesSourceMaps(config);
  config = withProguardRules(config);
  return config;
}

