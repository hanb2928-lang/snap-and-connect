const {
  withGradleProperties,
  withAppBuildGradle,
  withDangerousMod,
} = require('@expo/config-plugins');
const path = require('path');
const fs = require('fs');

// ── 1. gradle.properties tweaks ──────────────────────────────────────────────
function withGradleProps(config) {
  return withGradleProperties(config, (cfg) => {
    const props = cfg.modResults;

    function set(key, value) {
      const existing = props.find((p) => p.type === 'property' && p.key === key);
      if (existing) {
        existing.value = value;
      } else {
        props.push({ type: 'property', key, value });
      }
    }

    set('org.gradle.jvmargs', '-Xmx4096m -XX:MaxMetaspaceSize=1024m');
    set('reactNativeArchitectures', 'arm64-v8a,x86_64');
    set('EX_DEV_CLIENT_NETWORK_INSPECTOR', 'false');
    // Enable R8 minification and resource shrinking in release builds
    set('android.enableMinifyInReleaseBuilds', 'true');
    set('android.enableShrinkResourcesInReleaseBuilds', 'true');

    return cfg;
  });
}

// ── 2. hermesFlags in app/build.gradle ───────────────────────────────────────
function withHermesSourceMaps(config) {
  return withAppBuildGradle(config, (cfg) => {
    const contents = cfg.modResults.contents;

    // Avoid double-patching
    if (contents.includes('output-source-map')) {
      return cfg;
    }

    // Insert hermesFlags right before the autolinkLibrariesWithApp() line
    cfg.modResults.contents = contents.replace(
      /(\s*\/\* Autolinking \*\/\s*autolinkLibrariesWithApp\(\))/,
      `\n    // Generate source maps so minified stacks can be symbolicated\n    hermesFlags = ["-O", "-output-source-map"]\n$1`
    );

    return cfg;
  });
}

